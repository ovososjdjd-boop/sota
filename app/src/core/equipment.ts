/**
 * Кухонное оборудование: чем человек реально может готовить.
 *
 * Зачем это нужно. Приложение предлагало «Форель запечённую» и
 * «Творожную запеканку» человеку, у которого нет духовки, — рецепт
 * невыполним, и весь план рассыпается на первом же дне. Обратная
 * ошибка не менее вредна: у человека есть мультиварка, которая
 * готовит кашу без присмотра, но приложение об этом не знает
 * и режет ему меню лимитом времени.
 *
 * Оборудование — это не «настройка для гиков». В общежитии часто
 * только плитка и чайник; в съёмной квартире может не быть духовки;
 * у кого-то есть аэрогриль и микроволновка, но нет нормальной плиты.
 * Рецепт, который нечем приготовить, бесполезен независимо от того,
 * насколько он хорош по КБЖУ и цене.
 */

export type Equipment =
  | 'stove' // плита или варочная панель (конфорки)
  | 'oven' // духовка
  | 'microwave' // микроволновка
  | 'multicooker' // мультиварка, скороварка
  | 'blender' // блендер, погружной или чаша
  | 'freezer' // морозильная камера
  | 'kettle'; // чайник (в т.ч. для заваривания без плиты)

