/**
 * Набор по умолчанию — то, что есть практически у всех.
 *
 * Намеренно скромный: лучше недооценить кухню и предложить
 * выполнимое, чем составить меню, которое человек не сможет
 * приготовить. Духовка и мультиварка включаются явно.
 */
export const DEFAULT_EQUIPMENT: Equipment[] = ['stove', 'kettle', 'microwave', 'freezer'];

/**
 * Минимальный набор: только чайник и микроволновка.
 * Общежитие, офис, съём без кухни. Приложение обязано выдавать
 * осмысленный рацион даже здесь, а не разводить руками.
 */
export const MINIMAL_EQUIPMENT: Equipment[] = ['kettle', 'microwave'];

/**
 * Может ли человек приготовить блюдо своим набором техники.
 *
 * Правило простое: у рецепта есть список того, БЕЗ ЧЕГО его не сделать
 * (`requires`). Если чего-то нет — блюдо исключается из подбора.
 * Пустой список означает «ничего не нужно»: нарезать салат или
 * налить кефир можно и без кухни.
 */
export function canCook(
  requires: Equipment[] | undefined,
  available: Equipment[],
): boolean {
  if (!requires || requires.length === 0) return true;
  const have = new Set(available);
  return requires.every((e) => have.has(e));
}

/**
 * Ускорение готовки за счёт техники.
 *
 * Мультиварка не делает кашу быстрее по часам, но освобождает
 * человека: заложил крупу, ушёл. Для лимита «у меня 30 минут»
 * важно именно активное время, а не общее. То же с микроволновкой
 * при разогреве.
 *
 * Возвращает множитель к активному времени готовки.
 */
export function activeTimeFactor(
  requires: Equipment[] | undefined,
  available: Equipment[],
): number {
  const have = new Set(available);
  // Блюдо, которое умеет готовиться в мультиварке, при её наличии
  // требует от человека только загрузки продуктов.
  if (requires?.includes('multicooker') && have.has('multicooker')) return 0.4;
  // Духовка тоже работает сама: поставил противень и занимаешься своим.
  if (requires?.includes('oven') && have.has('oven')) return 0.7;
  return 1;
}
