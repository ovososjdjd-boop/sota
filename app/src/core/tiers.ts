/**
 * Классы продуктов и режимы рациона.
 *
 * ЗАЧЕМ. Раньше приложение решало одну и ту же задачу для всех:
 * «уложись в сумму и попади в норму». Но человек с 6 000 ₽ в месяц
 * и человек с 40 000 ₽ хотят разного, и оба недовольны одинаковым
 * алгоритмом:
 *
 *   бедный рацион  — нужно выжать максимум пользы из каждого рубля.
 *                    Дешёвые калории есть, а вот белка, овощей и
 *                    разнообразия при таких деньгах не хватает.
 *                    Задача: не «сэкономить», а НАКОРМИТЬ ХОРОШО.
 *   средний        — денег хватает на норму, остаётся на интерес.
 *                    Задача: сбалансированно + иногда что-то вкусное.
 *   богатый        — деньги не ограничивают. Экономить бессмысленно
 *                    и обидно: человек хочет качество и интересные
 *                    блюда, а приложение молча оставляло 4 000 ₽.
 *
 * Deaton & Subramanian и Darmon/Drewnowski показали: при жёстком
 * бюджете люди рационально смещаются к дешёвой энергии, теряя
 * микронутриенты. Это и есть то, с чем должен бороться бедный режим —
 * не с тратами, а с бедностью рациона.
 */

import type { Product, ProductCategory } from './types';

// ───────────────────────── Класс продукта ─────────────────────────

/**
 * Роль продукта в рационе с точки зрения денег и пользы.
 * Определяется не «дорого/дёшево вообще», а отношением цены
 * к тому, что продукт даёт.
 */
export type ProductTier =
  /** Основа: дешёвая энергия и база рациона — крупы, картофель, хлеб, масло */
  | 'staple'
  /** Необходимое: белок, овощи, молочное. Дороже, но без них рацион неполноценен */
  | 'essential'
  /** Приятное: то, что покупают ради удовольствия — сыр, орехи, красная рыба */
  | 'treat'
  /** Излишество: сладости. Пользы нет, только удовольствие */
  | 'indulgence'
  /**
   * Приправы и заварка: соль, чай, кофе, томатная паста, специи.
   *
   * Выделены отдельно, потому что не подчиняются логике остальных
   * классов. Соль стоит 35 ₽/кг и по формуле «дешёвая энергия»
   * не проходит (калорий ноль), а чай за 1284 ₽/кг формально
   * деликатес — хотя расходуется чайными ложками и стоит копейки
   * в пересчёте на порцию. Резать их в экономном режиме бессмысленно:
   * экономии не будет, а еда станет несъедобной.
   */
  | 'condiment';

export const TIER_LABEL: Record<ProductTier, string> = {
  staple: 'Основа',
  essential: 'Необходимое',
  treat: 'Вкусное',
  indulgence: 'Сладости',
  condiment: 'Приправы',
};

/**
 * Классификация продукта.
 *
 * Считается ИЗ ДАННЫХ, а не вручную по списку: база растёт, и ручной
 * список неизбежно рассинхронизируется. Критерии:
 *
 *   1. Сладости и снеки — всегда indulgence, независимо от цены.
 *      Дешёвый сахар не становится полезным оттого, что он дешёвый.
 *   2. Дешёвая энергия (крупы, мука, масло, хлеб, картофель) — staple.
 *   3. Источники белка и овощи по разумной цене — essential.
 *   4. Всё, что стоит заметно дороже медианы своей категории, — treat.
 */
export function classifyProduct(product: Product): ProductTier {
  const { category, pricePerKg, per100g, tags } = product;

  // Приправы — раньше всего остального: их логика особая (см. тип).
  // Мёд и варенье помечены и как condiment, и как сладость — здесь
  // важнее сладость, поэтому категория sweet проверяется первой.
  if (category === 'sweet') return 'indulgence';
  if (tags.includes('condiment')) return 'condiment';

  // цена тысячи килокалорий — честная мера «дешевизны» энергии
  const kcalPer1000 = per100g.kcal > 0 ? (pricePerKg / (per100g.kcal * 10)) * 1000 : Infinity;

  // Основа рациона: очень дешёвая энергия. Порог 60 ₽/1000 ккал взят
  // по фактическому разбросу базы (мука 18, крупы 20-37, хлеб 60).
  const STAPLE_CATEGORIES: ProductCategory[] = ['grain', 'bread', 'fat', 'legume'];
  if (STAPLE_CATEGORIES.includes(category) && kcalPer1000 <= 90) return 'staple';
  if (category === 'vegetable' && product.id === 'potato') return 'staple';

  // Деликатесы: то, что заметно дороже обычного в своей группе.
  // Красная рыба, сыр, орехи, ягоды — их едят ради удовольствия,
  // и в бедном рационе они первые кандидаты на вылет.
  if (category === 'nut') return 'treat';
  if (category === 'fish' && pricePerKg >= 700) return 'treat';
  if (category === 'meat' && pricePerKg >= 600) return 'treat';
  if (category === 'dairy' && pricePerKg >= 700) return 'treat';
  if (tags.includes('delicacy')) return 'treat';

  // Необходимое: белок, овощи, молочное, фрукты по нормальной цене.
  const ESSENTIAL: ProductCategory[] = [
    'meat', 'fish', 'dairy', 'egg', 'vegetable', 'fruit', 'legume', 'grain', 'bread',
  ];
  if (ESSENTIAL.includes(category)) return 'essential';

  return 'treat';
}

