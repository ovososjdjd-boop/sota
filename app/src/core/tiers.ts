export interface ModeProfile {
  mode: BudgetMode;
  /** Максимальная доля энергии из «вкусного» */
  maxTreatShare: number;
  /** Максимальная доля энергии из сладостей */
  maxIndulgenceShare: number;
  /** Минимальная доля энергии из «необходимого» — защита от пустых калорий */
  minEssentialShare: number;
  /** Вес награды за качественный белок */
  qualityWeight: number;
  /** Вес награды за разнообразие блюд */
  varietyWeight: number;
  /** Штраф за трату денег: >0 только когда экономия действительно нужна */
  thriftWeight: number;
  /** Целевая доля бюджета, которую стоит израсходовать */
  targetSpend: number;
}

